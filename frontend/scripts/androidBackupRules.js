/**
 * Android Auto Backup rules for Ischys.
 *
 * expo-secure-store ships rules that include only shared preferences, which
 * left the workout databases (files/SQLite/, one file per profile, plus the
 * owner's ischys.db that also lists the profiles) out of Google's backup and
 * out of phone-to-phone transfer. These rules add that folder and keep
 * SecureStore excluded: its values are encrypted with a Keystore key that
 * never leaves the device, so a restored copy could not be read.
 *
 * Android stops the app before a full backup, so the database and its WAL
 * files are copied at rest.
 */

const BACKUP_RULES = 'ischys_backup_rules';
const EXTRACTION_RULES = 'ischys_data_extraction_rules';

const RULES = [
  '<include domain="sharedpref" path="."/>',
  '<exclude domain="sharedpref" path="SecureStore"/>',
  '<include domain="file" path="SQLite/"/>',
];

const indent = (pad) => RULES.map((r) => `${pad}${r}`).join('\n');

/** Android 11 and lower (android:fullBackupContent). */
function backupRulesXml() {
  return `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by plugins/withAndroidBackupRules. Android 11 and lower. -->
<full-backup-content>
${indent('  ')}
</full-backup-content>
`;
}

/** Android 12 and higher (android:dataExtractionRules). */
function dataExtractionRulesXml() {
  return `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by plugins/withAndroidBackupRules. Android 12 and higher. -->
<data-extraction-rules>
  <cloud-backup>
${indent('    ')}
  </cloud-backup>
  <device-transfer>
${indent('    ')}
  </device-transfer>
</data-extraction-rules>
`;
}

/** Points the manifest's <application> at the rules above. */
function applyBackupAttributes(application) {
  const attrs = application.$;
  if (attrs['android:allowBackup'] === 'false') {
    throw new Error('withAndroidBackupRules: android:allowBackup is false, so these rules would never apply');
  }
  attrs['android:fullBackupContent'] = `@xml/${BACKUP_RULES}`;
  attrs['android:dataExtractionRules'] = `@xml/${EXTRACTION_RULES}`;
  return application;
}

module.exports = {
  BACKUP_RULES,
  EXTRACTION_RULES,
  backupRulesXml,
  dataExtractionRulesXml,
  applyBackupAttributes,
};
